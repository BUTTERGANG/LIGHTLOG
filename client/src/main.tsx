import React from 'react';
import ReactDOM from 'react-dom/client';
import { QueryClient, QueryClientProvider } from '@tanstack/react-query';
import App from './App';
import './index.css';

/**
 * Main Entry Point for LightLog Client
 *
 * IMPLEMENTATION NOTES FOR AI ARCHITECT:
 * - QueryClient configured for API state management
 * - Retry logic set to 1 for faster error feedback
 * - StrictMode enabled for development checks
 * - CSS imports Tailwind directives
 */

const queryClient = new QueryClient({
  defaultOptions: {
    queries: {
      retry: 1,
      refetchOnWindowFocus: false,
      staleTime: 5 * 60 * 1000, // 5 minutes
    },
  },
});

ReactDOM.createRoot(document.getElementById('root')!).render(
  <React.StrictMode>
    <QueryClientProvider client={queryClient}>
      <App />
    </QueryClientProvider>
  </React.StrictMode>
);
